export function imageForMarketProduct(name: string, category: string, current?: string) {
  const value = name.toLowerCase();
  const directMarketImage = directMarketProductImages[normalizeImageKey(name)];

  if (directMarketImage) return directMarketImage;
  if (value.includes('wheat') || value.includes('sharbati')) return directMarketProductImages.premiumsharbatiwheat;
  if (value.includes('rice') || value.includes('basmati') || value.includes('paddy')) return directMarketProductImages.basmatiricelonggrain;
  if (value.includes('maize') || value.includes('corn')) return directMarketProductImages.yellowmaizecorn;
  if (value.includes('ragi') || value.includes('finger millet')) return directMarketProductImages.fingermilletragi;
  if (value.includes('jowar') || value.includes('sorghum')) return directMarketProductImages.sorghumjowar;
  if (value.includes('bajra') || value.includes('pearl millet')) return directMarketProductImages.pearlmilletbajra;
  if (value.includes('toor') || value.includes('pigeon pea')) return agriEasyImages.toorDalPigeonPeas;
  if (value.includes('chana') || value.includes('chickpea')) return directMarketProductImages.splitchickpeachanadal;
  if (value.includes('moong') || value.includes('green gram')) return directMarketProductImages.greengrammoongdal;
  if (value.includes('onion')) return directMarketProductImages.redonions;
  if (value.includes('potato')) return directMarketProductImages.newcroppotatoes;
  if (value.includes('tomato')) return directMarketProductImages.farmfreshtomatoes;
  if (value.includes('brinjal') || value.includes('eggplant')) return directMarketProductImages.purplebrinjal;
  if (value.includes('mango')) return directMarketProductImages.premiummangoes;
  if (value.includes('banana')) return directMarketProductImages.organicbananas;
  if (value.includes('apple')) return directMarketProductImages.crispredapples;
  if (value.includes('curd') || value.includes('yogurt')) return directMarketProductImages.farmfreshcurd;
  if (value.includes('ghee')) return directMarketProductImages.purea2cowghee;
  if (value.includes('milk') || value.includes('dairy')) return agriEasyImages.freshBuffaloMilk;
  if (value.includes('tea')) return agriEasyImages.handpickedCtcTea;
  if (value.includes('coffee')) return agriEasyImages.coffee;
  if (value.includes('coconut')) return agriEasyImages.freshCoconuts;
  if (value.includes('turmeric')) return agriEasyImages.organicTurmericPowder;
  if (value.includes('chilli') || value.includes('chili')) return agriEasyImages.redChilli;
  if (value.includes('milk') || value.includes('curd') || value.includes('ghee')) return marketCategoryImages['Milk & Dairy'];
  if (value.includes('millet') || value.includes('ragi') || value.includes('bajra') || value.includes('jowar')) return marketCategoryImages.Millets;
  if (value.includes('dal') || value.includes('pea') || value.includes('gram')) return marketCategoryImages.Pulses;
  if (current && !current.includes('picsum.photos')) return current;

  return marketCategoryImages[category] || imageFallback;
}

export function imageForColdStorage(name: string, current?: string) {
  const key = normalizeImageKey(name);

  if (key.includes('nashikagrostorage')) return agriEasyImages.nashikAgroStorage;
  if (key.includes('delhifreshreserve')) return agriEasyImages.delhiFreshReserve;
  if (key.includes('gujaratseacool')) return agriEasyImages.gujaratSeaCool;

  return current || moduleImages.coldStorage;
}

type FpoImageSource = {
  name: string;
  services?: string[];
  tags?: string[];
  description?: string;
};

export function imageForFpo(fpo: FpoImageSource) {
  const value = [fpo.name, fpo.description, ...(fpo.services || []), ...(fpo.tags || [])]
    .join(' ')
    .toLowerCase();

  if (value.includes('tea')) return agriEasyImages.handpickedCtcTea;
  if (value.includes('dairy') || value.includes('milk')) return agriEasyImages.freshBuffaloMilk;
  if (value.includes('coffee')) return agriEasyImages.coffee;
  if (value.includes('millet')) return agriEasyImages.millets;
  if (value.includes('tech') || value.includes('precision') || value.includes('drone') || value.includes('iot')) return agriEasyImages.telanganaAgriHubFpo;
  if (value.includes('paddy') || value.includes('rice') || value.includes('basmati')) return directMarketProductImages.basmatiricelonggrain;
  if (value.includes('pulse') || value.includes('toor') || value.includes('lentil')) return agriEasyImages.toorDalPigeonPeas;
  if (value.includes('potato')) return directMarketProductImages.newcroppotatoes;
  if (value.includes('vegetable')) return marketCategoryImages.Vegetables;
  if (value.includes('chilli')) return agriEasyImages.redChilli;
  if (value.includes('spice') || value.includes('turmeric')) return agriEasyImages.organicTurmericPowder;
  if (value.includes('organic')) return agriEasyImages.organicCompostBag;

  return moduleImages.fpo;
}
